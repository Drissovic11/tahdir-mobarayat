import {cpSync,mkdirSync,existsSync,writeFileSync,readFileSync,readdirSync} from 'node:fs';
import {resolve,join,basename} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const output=resolve(process.argv[2]||join(root,'release/infinityfree'));
if(existsSync(output))throw new Error('Choisissez un nouveau répertoire de livraison vide.');
if(!existsSync(join(root,'backend/vendor/autoload.php')))throw new Error('composer install doit être exécuté avant la livraison.');
if(!existsSync(join(root,'frontend/dist/index.html')))throw new Error('Compiler le front avec VITE_CATALOG_API=/api/organizations et VITE_CONTENT_API=/api.');
const htdocs=join(output,'htdocs'),app=join(htdocs,'_app');mkdirSync(app,{recursive:true});
const excluded=new Set(['.env','.env.infinityfree.example','.git','node_modules','tests','public','composer.lock.tmp']);
cpSync(join(root,'backend'),app,{recursive:true,filter:src=>!excluded.has(basename(src))&&!src.includes('/storage/framework/views/')&&!src.includes('/storage/logs/')&&!src.includes('/bootstrap/cache/')});
for(const folder of ['storage/framework/views','storage/framework/sessions','storage/framework/cache/data','storage/logs','bootstrap/cache'])mkdirSync(join(app,folder),{recursive:true});
cpSync(join(root,'backend/public'),htdocs,{recursive:true});
cpSync(join(root,'frontend/dist'),htdocs,{recursive:true,filter:src=>basename(src)!=='index.html'});
cpSync(join(root,'frontend/dist/index.html'),join(htdocs,'frontend.html'));
cpSync(join(root,'backend/.env.infinityfree.example'),join(app,'.env.example'));
writeFileSync(join(app,'.htaccess'),'Require all denied\n');
writeFileSync(join(htdocs,'index.php'),`<?php
use Illuminate\\Http\\Request;
define('LARAVEL_START', microtime(true));
if (file_exists($maintenance = __DIR__.'/_app/storage/framework/maintenance.php')) require $maintenance;
require __DIR__.'/_app/vendor/autoload.php';
$app = require_once __DIR__.'/_app/bootstrap/app.php';
$app->usePublicPath(__DIR__);
$app->handleRequest(Request::capture());
`);
const htaccess=readFileSync(join(htdocs,'.htaccess'),'utf8').replace('<IfModule mod_rewrite.c>','<IfModule mod_rewrite.c>\n    RewriteRule ^_app(?:/|$) - [F,L]');
writeFileSync(join(htdocs,'.htaccess'),htaccess);
writeFileSync(join(output,'PREPARER-LES-CLES.mjs'),readFileSync(join(root,'scripts/prepare-installation.mjs'),'utf8'));
let files=0;function count(dir){for(const e of readdirSync(dir,{withFileTypes:true})){if(e.isDirectory())count(join(dir,e.name));else files++;}}count(output);
console.log(JSON.stringify({output,files,secretsIncluded:false}));
